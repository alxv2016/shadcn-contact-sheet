import { Button } from "@/registry/radix/ui/button"
import { CodeBlock, languageOf } from "@/editor/code-block"
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogHeader,
  DialogTitle,
  DialogTrigger,
} from "@/registry/radix/ui/dialog"
import { Tabs, TabsContent, TabsList, TabsTrigger } from "@/registry/radix/ui/tabs"
import {
  buildAdapterFiles,
  buildGlobalsCss,
  buildOverridesCss,
  buildShadcnThemeCss,
  TAILWIND_THEME_CSS,
  type ThemeConfig,
} from "@/theme/config"

